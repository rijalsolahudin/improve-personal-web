import {
  DEFAULT_THEME,
  THEME_NAMES,
  palette,
  semanticColors,
  themes,
  type ThemeName,
} from './colors.ts'
import { border, fontFamily, motion, radius, shadow, space, typography } from './scale.ts'

type TokenGroup = Readonly<Record<string, string>>

const declarations = (group: TokenGroup, indent = '  '): string =>
  Object.entries(group)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join('\n')

const aliases = (group: TokenGroup): TokenGroup =>
  Object.fromEntries(Object.entries(group).map(([name, source]) => [name, `var(--${source})`]))

const themeBlock = (name: ThemeName): string =>
  `[data-theme='${name}'] {\n${declarations(themes[name])}\n}`

/**
 * Render semua token jadi CSS custom properties.
 * Tema default ada di `:root`; tema lain di-override lewat `[data-theme]` di elemen mana pun.
 */
export function toCssVariables(): string {
  const root = [
    palette,
    themes[DEFAULT_THEME],
    radius,
    border,
    shadow,
    motion,
    space,
    fontFamily,
    typography,
    aliases(semanticColors),
  ]
    .map((group) => declarations(group))
    .join('\n')

  const overrides = THEME_NAMES.filter((name) => name !== DEFAULT_THEME).map(themeBlock)

  return [
    '/* Generated by @improve-personal/tokens - jangan diedit manual. */',
    `:root {\n${root}\n}`,
    ...overrides,
    '',
  ].join('\n')
}
